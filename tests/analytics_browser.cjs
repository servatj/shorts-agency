const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const browser = await chromium.launch({headless:true, executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || undefined});
  try {
    const page = await browser.newPage({viewport:{width:390,height:844}});
    page.setDefaultTimeout(5000);
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.route('https://**/*', route => route.request().url() === 'https://images.example/analytics-cover.svg' ? route.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="90" height="160"><rect width="90" height="160" fill="teal"/></svg>'}) : route.abort());
    await page.goto(process.env.TEST_URL);
    await page.locator('#username').fill('admin'); await page.locator('#password').fill(process.env.TEST_PASSWORD);
    await page.locator('#login-submit').click(); await page.locator('#workspace').waitFor({state:'visible'});
    const api = (path, body, method = 'POST') => page.evaluate(async ({path,body,method}) => {
      const me = await (await fetch('/auth/me')).json();
      const response = await fetch(path, {method,headers:{'Content-Type':'application/json','X-CSRF-Token':me.csrf_token}, ...(body === undefined ? {} : {body:JSON.stringify(body)})});
      if (!response.ok) throw new Error(await response.text()); return response.json();
    }, {path,body,method});
    const record = await api('/v1/shorts', {title:'Synthetic analytics',status:'published',script:'Immutable original',channel:'Canal de prueba',thumbnail_url:'https://images.example/analytics-cover.svg',preview_url:'https://www.instagram.com/reel/SYNTHETIC/'});
    const path = `/v1/shorts/${record.id}/metrics`;
    const raw = 'Observación pública puntual; no sincronización. Fuente: https://www.instagram.com/reel/SYNTHETIC/\nIdentificador: instagram:synthetic\nDatos originales: {"likes":{"value":999,"observed_at":"2026-10-30T12:00:00Z"}}';
    await api(path, {observed_at:'2026-10-30T12:00:00Z',source:'agent',likes:60,comments:1,notes:raw});
    await page.locator('#refresh-list').click(); await page.locator('#short-list .short-item').first().click();
    await page.locator('#metrics-tab').click();
    await page.waitForFunction(() => !document.querySelector('#metrics-message').textContent);
    assert.doesNotMatch(await page.locator('#metrics-panel').innerText(), /Datos originales|Identificador|\{|https:\/\//);
    assert.equal(await page.locator('[data-kpi="likes"] .kpi-value').innerText(), '60');
    assert.equal(await page.locator('[data-kpi="comments"] .kpi-value').innerText(), '1');
    assert.equal(await page.locator('[data-kpi="views"] .kpi-value').innerText(), '—');
    assert.match(await page.locator('[data-kpi="views"]').innerText(), /Sin dato/);
    assert.match(await page.locator('#metrics-context').innerText(), /Consulta pública/);
    assert.equal((await api(path, undefined, 'GET')).items[0].notes, raw);
    assert.equal(await page.locator('#detail > .detail-layout > .preview-panel').isVisible(), false);
    assert.equal(await page.locator('#script').getAttribute('readonly'), '');
    const refresh = async () => { await page.locator('#refresh-metrics').click(); await page.waitForFunction(() => !document.querySelector('#metrics-message').textContent); };
    const kpi = key => page.locator(`[data-kpi="${key}"] .kpi-value`).innerText();
    for (const width of [390,1536]) {
      await page.setViewportSize({width,height:1024});
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      const columns = await page.locator('#metrics-kpis').evaluate(e => getComputedStyle(e).gridTemplateColumns.split(' ').length);
      assert.equal(columns, width === 390 ? 2 : 4);
      await page.waitForFunction(() => document.querySelector('#metrics-context img')?.naturalWidth > 0);
      assert.equal(await page.locator('#metrics-context img').evaluate(e => getComputedStyle(e).objectFit), 'contain', 'Analytics cover must remain identifiable without cropping');
      if (width === 390) assert.ok(await page.locator('#metrics-kpis').evaluate(e => e.getBoundingClientRect().top + scrollY < 700), 'Metrics should be near the top on mobile');
      if (process.env.ANALYTICS_SCREENSHOTS) { require('node:fs').mkdirSync(process.env.ANALYTICS_SCREENSHOTS,{recursive:true}); await page.screenshot({path:`${process.env.ANALYTICS_SCREENSHOTS}/analytics-${width}.png`,fullPage:true}); }
    }
    await api(path, {observed_at:'2026-10-28T12:00:00Z',source:'manual',views:800,likes:100,notes:'Revisado a mano <b>sin etiquetas activas</b>'});
    await refresh(); assert.equal(await kpi('likes'),'60'); assert.equal(await kpi('views'),'—');
    await page.locator('#evolution-metric').selectOption('likes');
    await page.locator('#metrics-evolution svg').waitFor();
    assert.equal(await page.locator('#metrics-evolution circle').count(),2);
    assert.doesNotMatch(await page.locator('#metrics-evolution svg').evaluate(e=>e.outerHTML), /NaN|Infinity/);
    assert.match(await page.locator('#metrics-evolution svg desc').textContent(), /100.*60/);
    await page.locator('#evolution-metric').selectOption('views');
    assert.equal(await page.locator('#metrics-evolution svg').count(),0);
    assert.match(await page.locator('#metrics-evolution').innerText(), /Una observación disponible/);
    await page.locator('.metric-human-note summary').click();
    assert.match(await page.locator('.metric-human-note').innerText(), /<b>sin etiquetas activas<\/b>/);
    assert.equal(await page.locator('.metric-human-note b').count(),0);
    await api(path, {observed_at:'2026-10-30T12:00:00Z',source:'agent',likes:0,comments:0,notes:'Observación pública puntual; no sincronización. Fuente: javascript:alert(1)\nDatos originales: {bad}'});
    await refresh(); assert.equal(await kpi('likes'),'0'); assert.equal(await kpi('comments'),'0');
    assert.equal(await page.locator('#metrics-context a').count(),1);
    assert.doesNotMatch(await page.locator('#metrics-panel').innerText(), /javascript|Datos originales|Identificador|\{/);
    await page.locator('#evolution-metric').selectOption('likes');
    assert.equal(await page.locator('#metrics-evolution circle').count(),2);
    await api(path, {observed_at:'2026-10-29T12:00:00Z',source:'agent',notes:'{"unrecognized": [broken'});
    await refresh();
    assert.equal(await page.locator('#metrics-evolution polyline').count(),0, 'Missing metric breaks the line');
    assert.equal(await page.locator('#metrics-evolution circle').count(),2);
    await page.locator('#evolution-metric').selectOption('shares');
    assert.equal(await page.locator('#metrics-evolution svg').count(),0);
    assert.match(await page.locator('#metrics-evolution').innerText(), /Aún no hay datos suficientes/);
    const rawSnapshot = (await api(path,undefined,'GET')).items[0];
    const fixtureRead = async items => { await page.route(`**${path}`, route => route.fulfill({json:{items}})); await refresh(); };
    const endFixture = async () => { await page.unroute(`**${path}`); };
    for (const unsafe of ['javascript:alert(1)','data:text/html,test','http://example.test/a','https://user:pass@example.test/a','https://@example.test/a','https://example.test/\u007fa','https://example.test/\\a']) {
      await fixtureRead([{...rawSnapshot,notes:`Observación pública puntual; no sincronización. Fuente: ${unsafe}\nDatos originales: {}` }]);
      assert.equal(await page.locator('#metrics-context a').filter({hasText:'Ver fuente'}).count(),0,unsafe);
      await endFixture();
    }
    await fixtureRead([{...rawSnapshot,id:90,likes:12},{...rawSnapshot,id:91,likes:9}]);
    await page.locator('#evolution-metric').selectOption('likes');
    assert.equal(await kpi('likes'),'9'); assert.equal(await page.locator('#metrics-evolution svg').count(),0);
    await endFixture();
    await fixtureRead([{...rawSnapshot,observed_at:'not a timestamp',likes:500},{...rawSnapshot,id:92,likes:8}]);
    assert.equal(await kpi('likes'),'8'); assert.equal(await page.locator('#metrics-evolution svg').count(),0);
    await endFixture(); await refresh();
    await page.locator('#metric-entry summary').click();
    assert.equal(await page.locator('#views').inputValue(),'');
    await page.locator('#likes').fill('-1'); await page.locator('#save-metric').click();
    assert.equal((await api(path,undefined,'GET')).items.length,4);
    await page.locator('#likes').fill('5');
    page.once('dialog',d=>d.dismiss()); await page.locator('#back-videos').click();
    assert.equal(await page.locator('#likes').inputValue(),'5');
    await page.locator('#observed_at').fill('2026-10-31T12:00');
    await page.locator('#average_view_duration_seconds').fill('12.5');
    await page.locator('#retention_percent').fill('40');
    await page.locator('#metric-notes').fill('Observación manual comprobada');
    await page.locator('#save-metric').click();
    await page.waitForFunction(() => document.querySelector('#global-message').textContent.includes('Captura guardada'));
    assert.equal(await kpi('likes'),'5'); assert.equal(await kpi('views'),'—');
    assert.equal(await page.locator('.metric-history-row').count(),5);
    assert.match(await page.locator('#metrics-retention').innerText(), /40 %.*12,5 s/);
    const saved = (await api(path,undefined,'GET')).items;
    assert.equal(saved.at(-1).views,null); assert.equal(saved.at(-1).source,'manual'); assert.equal(saved[0].notes,raw);
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    assert.doesNotMatch(await page.locator('#metrics-panel').innerText(), /Datos originales|Identificador|\{|https:\/\//);
    if (process.env.ANALYTICS_SCREENSHOTS) await page.screenshot({path:`${process.env.ANALYTICS_SCREENSHOTS}/analytics-history-chart-390.png`,fullPage:true});
    await page.locator('#editor-tab').click(); assert.equal(await page.locator('#detail > .detail-layout > .preview-panel').isVisible(),true);
    assert.equal(await page.locator('#script').getAttribute('readonly'),'');
    await page.locator('#metrics-tab').click(); await page.waitForFunction(() => !document.querySelector('#metrics-message').textContent);
    // Fault injection only for read errors/races; creates and save/readback above use real HTTP/SQLite.
    let release; let started;
    const begun = new Promise(resolve=>started=resolve);
    await page.route(`**${path}`, async route => { started(); await new Promise(resolve=>release=resolve); await route.fulfill({json:{items:saved}}); });
    await page.locator('#refresh-metrics').click(); await begun;
    assert.equal(await page.locator('#metrics-kpis').innerText(),'');
    assert.equal(await page.locator('#metrics-evolution svg').count(),0);
    const other = await api('/v1/shorts',{title:'Synthetic empty'});
    await page.locator('#back-videos').click(); await page.locator('#refresh-list').click();
    await page.getByRole('button').filter({hasText:'Synthetic empty'}).first().click();
    await page.locator('#metrics-tab').click(); await page.waitForFunction(() => !document.querySelector('#metrics-message').textContent);
    release(); await page.waitForTimeout(150);
    assert.match(await page.locator('#metrics-history').innerText(), /Todavía no hay observaciones/);
    assert.equal(await kpi('likes'),'—');
    await page.unroute(`**${path}`);
    await page.route(`**/v1/shorts/${other.id}/metrics`,route=>route.fulfill({status:500,json:{}}));
    await page.locator('#refresh-metrics').click(); await page.waitForFunction(() => document.querySelector('#metrics-message').classList.contains('error'));
    assert.equal(await page.locator('#metrics-kpis').innerText(),'');
    assert.equal(await page.locator('#metrics-history').innerText(),'');
    await page.locator('#metric-entry summary').click(); await page.locator('#likes').fill('9');
    page.once('dialog', d=>d.accept());
    await page.locator('#new-short').click(); await page.locator('#metrics-tab').click();
    assert.match(await page.locator('#metrics-message').innerText(), /Guarda primero/);
    assert.equal(await page.locator('#metric-entry').isVisible(),false);
    assert.equal(await page.locator('#refresh-metrics').isVisible(),false);
    assert.deepEqual(errors, []);
    console.log('Analytics acceptance passed: typed values, provenance safety, null/zero, real save/readback, timestamps, decreasing counters, gaps, selector, mobile/desktop, guards, lock, empty/error/race isolation.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
