const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const browser = await chromium.launch({headless:true, executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || undefined});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000}, timezoneId:'UTC'});
    page.setDefaultTimeout(3000);
    const errors = [], external = [];
    page.on('pageerror', e => errors.push(e.message));
    const stamp = '2026-10-30T12:00:00Z';
    const source = 'https://www.youtube.com/@synthetic';
    const metric = (value, display = null, approximate = false) => ({value,display,approximate,source_url:source,observed_at:stamp});
    const data = {status:'ok',attempted_at:stamp,source_url:source,canonical_url:source,source_method:'public_page',profile:{display_name:'Public name',description:'Synthetic biography'},metrics:{subscribers:metric(1200,'1.2K',true),posts:metric(0)},catalog_status:'partial',publications_collected:3,notes:[]};
    const accounts = [{id:'sample',name:'Synthetic channel',platform:'youtube',profile_url:source,public_data:data,sync_status:'not_connected'}];
    const published = {id:1,title:'Synthetic publication',script:'',status:'published',language:'es',format:'9:16',social_account_id:'sample'};
    await page.route('**/*', async route => {
      const url = new URL(route.request().url());
      if (url.origin !== 'http://fixture.test') { external.push(url.href); return route.abort(); }
      let json;
      if (url.pathname === '/auth/me') json = {user:{username:'synthetic'},csrf_token:'synthetic'};
      else if (url.pathname === '/v1/social-accounts') json = {items:accounts};
      else if (url.pathname === '/v1/shorts') json = {items:[published]};
      else if (url.pathname === '/v1/shorts/1') json = published;
      if (json) return route.fulfill({json});
      const filename = url.pathname.startsWith('/static/') ? path.basename(url.pathname) : 'index.html';
      return route.fulfill({body:fs.readFileSync(path.join(__dirname,'../static',filename)),contentType:filename.endsWith('.js')?'application/javascript':filename.endsWith('.css')?'text/css':'text/html'});
    });
    await page.goto('http://fixture.test/');
    await page.locator('#workspace').waitFor({state:'visible'});
    const choose = async id => { await page.locator('#channel-toggle').click(); await page.locator(`.channel-choice[data-channel="${id}"]`).click(); };
    await choose('sample');
    assert.match(await page.locator('#channel-summary').innerText(), /Synthetic channel/);
    assert.match(await page.locator('#channel-summary').innerText(), /≈ 1.2K/);
    assert.match(await page.locator('#channel-summary').innerText(), /3 enlaces recopilados/);
    assert.equal(await page.locator('[data-public-metric="posts"] dd').textContent(), '0');
    const refresh = async () => { await page.locator('#channel-toggle').click(); await page.locator('#refresh-social').click(); await page.waitForFunction(() => !document.querySelector('#refresh-social').disabled); await page.locator('#social-search').press('Escape'); };
    assert.deepEqual(await page.locator('.rail nav button').allTextContents(), ['Inicio','Vídeos']);
    const observed = await page.evaluate(value => new Intl.DateTimeFormat('es-ES',{dateStyle:'medium',timeStyle:'short'}).format(new Date(value)), stamp);
    assert.match(await page.locator('#channel-summary').innerText(), new RegExp(observed));
    assert.equal(await page.locator('#channel-summary a').first().getAttribute('href'), source);
    assert.ok((await page.locator('#channel-summary a').first().getAttribute('rel')).includes('noopener'));
    await page.locator('#channel-toggle').click();
    assert.match(await page.locator('.channel-option').filter({has:page.locator('[data-channel="sample"]')}).getAttribute('title'), /1.2K.*public_page/);
    await page.locator('#social-search').press('Escape');
    accounts[0].analytics = {subscribers:700,basis:'screenshot_not_live',observed_at:null,note:'Historical only'};
    data.metrics.followers = metric(null);
    data.profile.description = '<img src="https://external.test/x" onerror="alert(1)">';
    data.profile.avatar_url = 'https://external.test/avatar';
    data.notes = ['<script>alert(1)</script>'];
    data.metrics.likes = {...metric(0),source_url:'javascript:alert(1)'};
    await refresh();
    assert.equal(await page.locator('[data-public-metric="followers"] dd').textContent(), '—');
    assert.equal(await page.locator('[data-public-metric="likes"] dd').textContent(), '0');
    assert.match(await page.locator('.channel-screenshot').innerText(), /700 suscriptores.*NO en directo.*Fecha de captura desconocida/);
    assert.equal(await page.locator('[data-public-metric="subscribers"] dd').textContent(), '≈ 1.2K');
    assert.match(await page.locator('.channel-bio').textContent(), /<img/);
    await page.locator('#channel-summary details summary').click();
    assert.match(await page.locator('#channel-summary').innerText(), /<script>/);
    assert.equal(await page.locator('#channel-summary img, #channel-summary script, #channel-summary [style], #channel-summary a[href^="javascript:"]').count(), 0);
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    for (const [status,label] of [['blocked','Consulta pública bloqueada'],['missing_url','Falta enlace exacto'],['identity_mismatch','Identidad no coincidente'],['not_found','Perfil no encontrado']]) {
      data.status = status; await refresh();
      assert.ok((await page.locator('#channel-summary').innerText()).includes(label));
      assert.equal(await page.locator('[data-public-metric]').count(), 0);
      assert.ok(!(await page.locator('#channel-summary').innerText()).includes('1.2K'));
    }
    delete accounts[0].public_data; await refresh();
    assert.match(await page.locator('#channel-summary').innerText(), /No consultado/);
    accounts[0].public_data = data; data.status = 'partial'; data.metrics = {}; await refresh();
    assert.equal(await page.locator('[data-public-metric="posts"] dd').textContent(), '—');
    await choose('');
    assert.match(await page.locator('#channel-summary').innerText(), /1 de 1 canales/);
    assert.equal(await page.locator('#channel-summary details').getAttribute('open'), null);
    await page.locator('#short-list .short-item').click();
    await page.locator('#script-reading').waitFor({state:'visible'});
    assert.equal(await page.locator('#script-reading').innerText(), 'Guion no disponible');
    assert.equal(await page.locator('#edit-script').isVisible(), false);
    await page.locator('#back-videos').click();
    assert.equal(await page.locator('.inspector-script').innerText(), 'Guion no disponible');
    await page.locator('#new-short').click();
    await page.locator('#script').fill('Unsaved synthetic script');
    page.once('dialog', dialog => dialog.dismiss()); await choose('sample');
    assert.equal(await page.locator('#script').inputValue(), 'Unsaved synthetic script');
    assert.match(await page.locator('#channel-summary').innerText(), /1 de 1 canales/);
    assert.deepEqual(external, []);
    assert.deepEqual(errors, []);
    console.log('Channel-data browser: metadata, provenance, statuses, safety, mobile and edit guard passed');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode=1; });
