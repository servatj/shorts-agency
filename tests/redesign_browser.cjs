const assert = require('node:assert/strict');
module.exports = async function redesign(page, full) {
  const choose = async id => {
    await page.locator('#channel-toggle').click();
    await page.locator('#social-search').fill('');
    await page.locator(`.channel-choice[data-channel="${id}"]`).click();
  };
  assert.equal(await page.locator('#short-list .short-item').count(), 2);
  await choose('__none');
  assert.equal(await page.locator('#short-list .short-item').count(), 1);
  await choose('youtube:sample_account_00');
  assert.equal(await page.locator('#short-list .short-item').count(), 1);
  await choose('');
  await page.locator('#short-list .short-item').filter({hasText:'Guion QA'}).click();
  const unsaved = full + '\nNO PERDER';
  await page.locator('#script').fill(unsaved);
  const cancel = d => d.dismiss();
  page.once('dialog', cancel);
  await page.locator('#library-home').click();
  assert.equal(await page.locator('#detail').isVisible(), true);
  assert.equal(await page.locator('#script').inputValue(), unsaved);
  await page.locator('#channel-toggle').click();
  page.once('dialog', cancel);
  await page.locator('.channel-choice[data-channel="__none"]').click();
  assert.match(await page.locator('#channel-toggle').textContent(), /Todos los canales/);
  assert.equal(await page.locator('#script').inputValue(), unsaved);
  await page.locator('#social-search').press('Escape');
  page.once('dialog', cancel);
  await page.locator('#new-short').click();
  assert.equal(await page.locator('#script').inputValue(), unsaved);
  page.once('dialog', d => { assert.equal(d.type(), 'beforeunload'); return d.dismiss(); });
  await page.goto(process.env.TEST_URL + '/videos').catch(error => { assert.match(error.message, /ERR_ABORTED|Navigation/); });
  assert.equal(await page.locator('#script').inputValue(), unsaved);
  // Real concurrent API update: another editor records publication.
  const result = await page.evaluate(async () => {
    const me = await (await fetch('/auth/me')).json();
    const items = (await (await fetch('/v1/shorts')).json()).items;
    const record = items.find(i => i.title.startsWith('Guion QA'));
    const r = await fetch('/v1/shorts/' + record.id, {method:'PATCH', headers:{'Content-Type':'application/json','X-CSRF-Token':me.csrf_token}, body:JSON.stringify({status:'published'})});
    return r.status;
  });
  assert.equal(result, 200);
  await page.locator('#save-short').click();
  await page.locator('#recovery-panel').waitFor({state:'visible'});
  assert.equal(await page.locator('#recovery-script').inputValue(), unsaved);
  assert.match(await page.locator('#global-message').textContent(), /Conflicto/);
  assert.equal(await page.locator('#script-reading').textContent(), full);
  assert.equal(await page.locator('#save-short').isVisible(), false);
  assert.equal(await page.locator('#edit-script').isVisible(), false);
  assert.equal(await page.locator('#status option').count(), 1);
  assert.equal(await page.locator('#status').inputValue(), 'published');
  page.once('dialog', d => d.accept());
  await page.locator('#dismiss-recovery').click();
  await page.locator('#summary-tab').click();
  await page.locator('#notes').fill('Metadatos tras publicación');
  await page.locator('#youtube_url').fill('https://youtu.be/SAMPLE00001');
  await page.locator('#format').selectOption('16:9');
  await page.locator('#save-short').click();
  await page.waitForFunction(() => document.querySelector('#save-state').textContent === 'Guardado');
  assert.equal(await page.locator('#preview-content iframe').count(), 0);
  await page.getByRole('button', {name:'Cargar vista previa', exact:true}).click();
  assert.match(await page.locator('#preview-content iframe').getAttribute('src'), /youtube-nocookie.com\/embed\/SAMPLE00001/);
  assert.equal(await page.locator('#preview-stage').evaluate(e => e.classList.contains('landscape')), true);
  await page.locator('#metrics-tab').click();
  await page.locator('#metric-entry summary').click();
  await page.locator('#views').fill('12');
  await page.locator('#likes').fill('0');
  await page.locator('#save-metric').click();
  await page.waitForFunction(() => document.querySelector('#metrics-history').textContent.includes('captura registrada'));
  const metrics = await page.evaluate(async () => {
    const items = (await (await fetch('/v1/shorts')).json()).items;
    const record = items.find(i => i.title.startsWith('Guion QA'));
    return (await (await fetch('/v1/shorts/' + record.id + '/metrics')).json()).items;
  });
  assert.equal(metrics.length, 1); assert.equal(metrics[0].views, 12); assert.equal(metrics[0].likes, 0); assert.equal(metrics[0].comments, null);
  await page.locator('#editor-tab').click();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const boxes = await page.evaluate(() => ({script:document.querySelector('#editor-panel').getBoundingClientRect().bottom, preview:document.querySelector('#detail .preview-panel').getBoundingClientRect().top}));
  assert.ok(boxes.preview > boxes.script);
  await page.locator('#back-videos').click();
  await page.locator('#short-list .short-item').filter({hasText:'Sin guion'}).click();
  await page.locator('#publication-tab').click();
  assert.match(await page.locator('#publication-panel').innerText(), /No publica/);
  page.once('dialog', async d => { assert.match(d.message(), /irreversible/); await d.dismiss(); });
  await page.locator('#publish-short').click();
  assert.match(await page.locator('#detail-status').textContent(), /Borrador/);
  page.once('dialog', d => d.accept());
  await page.locator('#publish-short').click();
  await page.waitForFunction(() => document.querySelector('#detail-status').textContent === 'Publicado');
  await page.locator('#back-videos').click();
};

